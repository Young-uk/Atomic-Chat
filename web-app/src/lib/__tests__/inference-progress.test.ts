import { beforeEach, expect, it } from 'vitest'
import { observeInferenceProgress, useInferenceProgress } from '../inference-progress'
beforeEach(() => useInferenceProgress.setState({ byThread: {} }))
it('accepts fragmented progress followed by reasoning and text', () => {
  const observer = observeInferenceProgress('a')
  observer.push(': atomic-prog')
  expect(useInferenceProgress.getState().byThread.a.phase).toBe('waiting')
  observer.push('ress {"processed":20,"total":80,"cache":32000}\r\n\r\n')
  expect(useInferenceProgress.getState().byThread.a).toMatchObject({ phase: 'reading', processed: 20, total: 80, cache: 32000 })
  observer.push(': atomic-progress {"processed":80,"total":80,"cache":32000}\n\n')
  expect(useInferenceProgress.getState().byThread.a.phase).toBe('preparing')
  observer.push('data: {"choices":[{"delta":{"content":"answer"}}]}\n\n')
  expect(useInferenceProgress.getState().byThread.a.phase).toBe('generating')
  observer.finish()
  expect(useInferenceProgress.getState().byThread.a).toBeUndefined()
})
it('rejects invalid counts and tolerates comments and malformed events', () => {
  const observer = observeInferenceProgress('a')
  observer.push(': prefill\n\ndata: invalid\n: atomic-progress {"processed":-1,"total":2,"cache":0}\n')
  observer.push(': atomic-progress {"processed":5,"total":2,"cache":0}\n')
  expect(useInferenceProgress.getState().byThread.a.phase).toBe('waiting')
})
it('isolates threads and rejects updates and completion from an older request', () => {
  const older = observeInferenceProgress('a')
  const newer = observeInferenceProgress('a')
  const other = observeInferenceProgress('b')
  older.push(': atomic-progress {"processed":1,"total":2,"cache":0}\n')
  older.finish()
  expect(useInferenceProgress.getState().byThread.a.phase).toBe('waiting')
  newer.finish()
  older.push(': atomic-progress {"processed":1,"total":2,"cache":0}\n')
  expect(useInferenceProgress.getState().byThread.a).toBeUndefined()
  expect(useInferenceProgress.getState().byThread.b).toBeDefined()
  other.finish()
})
