import { beforeEach, expect, it } from 'vitest'
import { observeInferenceProgress, useInferenceProgress } from '../inference-progress'
beforeEach(() => useInferenceProgress.setState({ byThread: {}, contextByThread: {} }))
it('accepts fragmented progress followed by reasoning and text', () => {
  const observer = observeInferenceProgress('a')
  observer.push(': atomic-prog')
  expect(useInferenceProgress.getState().byThread.a.phase).toBe('waiting')
  observer.push('ress {"processed":20,"total":80,"cache":32000}\r\n\r\n')
  expect(useInferenceProgress.getState().byThread.a).toMatchObject({ phase: 'reading', processed: 20, total: 80, cache: 32000 })
  observer.push(': atomic-progress {"processed":80,"total":80,"cache":32000}\n\n')
  expect(useInferenceProgress.getState().byThread.a.phase).toBe('preparing')
  observer.push('data: {"choices":[{"delta":{"content":"answer"}}]}\n\n')
  expect(useInferenceProgress.getState().byThread.a.phase).toBe('generating')
  observer.finish()
  expect(useInferenceProgress.getState().byThread.a).toBeUndefined()
})
it('rejects invalid counts and tolerates comments and malformed events', () => {
  const observer = observeInferenceProgress('a')
  observer.push(': prefill\n\ndata: invalid\n: atomic-progress {"processed":-1,"total":2,"cache":0}\n')
  observer.push(': atomic-progress {"processed":5,"total":2,"cache":0}\n')
  expect(useInferenceProgress.getState().byThread.a.phase).toBe('waiting')
})
it('isolates threads and rejects updates and completion from an older request', () => {
  const older = observeInferenceProgress('a')
  const newer = observeInferenceProgress('a')
  const other = observeInferenceProgress('b')
  older.push(': atomic-progress {"processed":1,"total":2,"cache":0}\n')
  older.finish()
  expect(useInferenceProgress.getState().byThread.a.phase).toBe('waiting')
  newer.finish()
  older.push(': atomic-progress {"processed":1,"total":2,"cache":0}\n')
  expect(useInferenceProgress.getState().byThread.a).toBeUndefined()
  expect(useInferenceProgress.getState().byThread.b).toBeDefined()
  other.finish()
})

it('keeps full prompt usage after reading and ignores stale observers', () => {
  const old = observeInferenceProgress('a')
  const current = observeInferenceProgress('a')
  current.push(': atomic-progress {"processed":20,"total":80,"cache":32000}\n')
  expect(useInferenceProgress.getState().contextByThread?.a.tokens).toBe(32080)
  old.push(': atomic-progress {"processed":1,"total":2,"cache":0}\n')
  current.finish()
  expect(useInferenceProgress.getState().contextByThread?.a.tokens).toBe(32080)
})

it('carries the runtime scope through live and completed foreground observations', () => {
  const observer = observeInferenceProgress('scoped', 'model-a', 'runtime-a')
  observer.push(': atomic-progress {"processed":20,"total":80,"cache":32000}\n')
  expect(useInferenceProgress.getState().byThread.scoped.usageScope).toBe('runtime-a')
  expect(useInferenceProgress.getState().contextByThread?.scoped).toMatchObject({ modelId: 'model-a', usageScope: 'runtime-a', tokens: 32080 })
  observer.finish()
  expect(useInferenceProgress.getState().contextByThread?.scoped.usageScope).toBe('runtime-a')
})

it('normalizes fragmented Strata progress while keeping full context usage', () => {
  const observer = observeInferenceProgress('a')
  observer.push('data: {"prompt_pro')
  observer.push('gress":{"processed":32020,"total":32080,"cache":32000},"choices":[{"delta":{}}]}\n\n')
  expect(useInferenceProgress.getState().byThread.a).toMatchObject({ phase: 'reading', processed: 20, total: 80, cache: 32000 })
  expect(useInferenceProgress.getState().contextByThread?.a.tokens).toBe(32080)
  observer.push('data: {"prompt_progress":{"processed":31999,"total":32080,"cache":32000}}\n')
  expect(useInferenceProgress.getState().byThread.a.processed).toBe(20)
  observer.push('data: {"choices":[{"delta":{"content":"answer"}}]}\n')
  expect(useInferenceProgress.getState().byThread.a.phase).toBe('generating')
})

it('does not regress decoding to preparation when late prefill heartbeats arrive', () => {
  const observer = observeInferenceProgress('a')
  observer.push('data: {"choices":[{"delta":{"content":"answer"}}]}\n\n')
  observer.push(': atomic-progress {"processed":100,"total":100,"cache":20}\n\n')
  observer.push('data: {"prompt_progress":{"processed":120,"total":120,"cache":20}}\n\n')
  expect(useInferenceProgress.getState().byThread.a.phase).toBe('generating')
  observer.finish()
  const next = observeInferenceProgress('a')
  next.push(': atomic-progress {"processed":1,"total":100,"cache":20}\n\n')
  expect(useInferenceProgress.getState().byThread.a.phase).toBe('reading')
  next.finish()
})
